def _get_canned_text(agent_name: str) -> str:
    """Return canned text for the given agent name."""
    key = agent_name.lower()
    for pattern, text in _CANNED_TEXT.items():
        if pattern in key:
            return text
    return _CANNED_TEXT["default"]


class StructuredMockRunner:
    """Mock equivalent of StructuredLLMRunner."""

    def __init__(self, parent: "MockLLMClient", schema: Type[Any]):
        self.parent = parent
        self.schema = schema

    def run(self, input_data: Any, config: Optional[Any] = None, timeout: Optional[int] = None, **kwargs: Any) -> Any:
        return self.parent._mock_structured(self.schema)


class MockLLMClient:
    """Mock LLM client that returns canned responses without API calls."""

    def __init__(self, name: str = "MockAgent", verbose: bool = False, model_name: Optional[str] = None, **kwargs):
        self.name = name
        self.verbose = verbose
        self.model_name = model_name or "mock"

    @staticmethod
    def _mock_usage() -> Dict[str, int]:
        return {
            "prompt_tokens": 100,
            "completion_tokens": 200,
            "total_tokens": 300,
            "input_tokens": 100,
            "output_tokens": 200,
        }

    def _mock_structured(self, schema: Type[Any]) -> Any:
        """Return a structurally valid instance of the given Pydantic schema."""
        schema_name = schema.__name__ if hasattr(schema, "__name__") else str(schema)

        # Try to find a canned JSON for this specific schema
        canned_key = schema_name.lower()
        for pattern, text in _CANNED_TEXT.items():
            if pattern in canned_key:
                try:
                    if hasattr(schema, "model_validate_json"):
                        return schema.model_validate_json(text)
                except Exception:
                    pass

        # Fallback: construct with defaults
        if hasattr(schema, "model_construct"):
            try:
                return schema.model_construct()
            except Exception:
                pass

        # Last resort: try empty construction
        try:
            return schema()
        except Exception:
            raise RuntimeError(
                f"MockLLMClient cannot construct {schema_name}. "
                f"Add a canned response for this schema in mock_llm.py."
            )

    def run_text(self, input_data: Any, config: Optional[Any] = None, timeout: Optional[int] = None, **kwargs: Any) -> LLMTextResponse:
        """Return canned text response."""
        if self.verbose:
            print(f"    [MOCK LLM] {self.name} returning canned text response.")
        return LLMTextResponse(
            content=_get_canned_text(self.name),
            usage_metadata=self._mock_usage(),
        )

    def structured(self, schema: Type[Any]) -> StructuredMockRunner:
        """Return a mock structured runner."""
        return StructuredMockRunner(self, schema)

