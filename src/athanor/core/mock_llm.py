def is_mock_enabled() -> bool:
    """Check whether mock mode is active."""
    if os.getenv("ATHANOR_MOCK_LLM", "").strip() in ("1", "true", "yes"):
        return True
    return (config.llm_provider or "").lower() == "mock"


